def scan_bin_universe(path, rename):
    """Turnover universe straight out of a price bin -> (symbols, that bin's last bar date).

    ⚠️ Map every bin symbol through `rename` — the committed bin lags a rename (it is refreshed on its
    own cadence), so it can still hold the OLD key while fundamentals/sf_revop have already moved to the
    NEW one (DATA_RUNBOOK §30 step 4 deletes the old key). Without this the company matches NOTHING and
    silently leaves the 'liquid' universe: GUJGASLTD→GUJENERGY (eff 2026-07-01) dropped out of all 29
    quarters this way. §30 step 4b names this map as exactly that bin-key bridge for this build; index
    membership already applies it (snap_as_of), the turnover set did not.

    ⚠️ RECENCY GUARD (added 2026-08-10, DATA_RUNBOOK §11). The screen takes each symbol's LAST
    `TURN_WINDOW` BARS **whenever they happened**. When a symbol's series simply STOPS, those are its last
    live bars, so it keeps passing a screen whose own note promises "currently-listed companies trading
    ≥₹1cr/day" — off bars up to 17 years old. `alive` cannot catch it: bin meta is frozen alongside the
    bin, so it still reads stale-True. Fix: require the symbol's LAST bar to be within RECENCY_DAYS of the
    bin's OWN `end` — NOT of today's date. The fallback bin is a frozen snapshot and must be judged
    against itself, or a stale-but-valid bin would screen out its whole universe.

    ⚠️ These are NOT dead companies — do not repeat that. All 8 flagged on the committed bin were checked
    against NSE's EQUITY_L.csv and Yahoo on 2026-08-10 and EVERY ONE still trades. Two real causes:
      · LEFT THE NSE CASH SEGMENT, still on BSE (absent from EQUITY_L.csv; .BO has full bars, .NS none):
        SPSL, RDEL(→RNAVAL), HSIL(→AGI), SPICEJET, LANCER, HINDMOTORS, CRANESSOFT. This bin is NSE-sourced,
        so it CANNOT measure their turnover — dropping them is the screen telling the truth.
      · NSE-LISTED IN SERIES **BZ**, which our own ingestion drops class-wide — build_sf_data.py:73 keeps
        only ("EQ","BE"). Measured: of NSE's 39 BZ symbols 38 are stale in the bin, vs 0 of 2,086 EQ and
        0 of 285 BE. That is HDIL and RAJESHEXPO: both trading on NSE today, both invisible to us since
        they were penalised into BZ. The guard is right to drop them (we have no current turnover for
        them) but the underlying feed gap is a SEPARATE defect — hence the loud per-symbol log below.
    A rename is harmless here: HSIL's stale key is dropped, but its target AGI is fresh and stays in.

    Why 60 days: measured to sit inside an EMPTY gap, not tuned to taste. On both bins the age-of-last-bar
    histogram is bimodal with NOTHING in between — committed bin (end 2026-06-13): 1,426 of 1,434 passers
    are ≤7d, then a hole all the way to 171d; fresh release bin (end 2026-08-07): 1,441 of 1,447 are ≤7d,
    then a hole to 226d. Every cutoff from ~8d to ~170d yields the IDENTICAL membership, so 60d (≈40
    sessions) buys a wide margin for a genuine trading halt without letting a stale series back in.
    NOTE this tests only the LAST bar, never gaps: a stock suspended for months and then RESUMED has a
    recent last bar and stays in, which is right — it is trading now. Only one still dark at `end` drops."""
    D = json.loads(gzip.decompress(open(path, "rb").read()))
    meta, data = D["meta"], D["data"]
    end = D.get("end")
    cutoff = None  # YYYYMMDD int, comparable straight against a `d` entry
    try:
        e = datetime.date(*(int(x) for x in str(end).split("-")))
        c0 = e - datetime.timedelta(days=RECENCY_DAYS)
        cutoff = c0.year * 10000 + c0.month * 100 + c0.day
    except Exception:
        print(f"  ⚠ bin has no usable `end` ({end!r}) — RECENCY GUARD IS OFF, stale series may pass")
    U, stale = set(), []
    for s, m in meta.items():
        if not isinstance(m, dict) or m.get("alive") is False:
            continue
        ser = data.get(s)
        if not ser:
            continue
        c, v = ser.get("c"), ser.get("v")
        if not c or not v:
            continue
        n = min(len(c), len(v))
        vals = [c[i] * v[i] / 1e7 for i in range(max(0, n - TURN_WINDOW), n) if c[i] and v[i]]
        vals = [x for x in vals if x > 0]
        if not (vals and statistics.median(vals) >= TURN_FLOOR_CR):
            continue
        if cutoff is not None:
            d = ser.get("d")
            # no dates at all == cannot PROVE it still trades; drop it rather than guess (CLAUDE.md).
            if not d or d[-1] < cutoff:
                stale.append((s, (d[-1] if d else None)))
                continue
        U.add(rename.get(s, s))
    if stale:
        stale.sort(key=lambda t: (t[1] is not None, t[1]))
        print(
            "  recency guard (last bar within %dd of %s): dropped %d — %s"
            % (RECENCY_DAYS, end, len(stale), ", ".join(f"{s}@{d}" for s, d in stale))
        )
    return U, end


def build_liquid_universe(rename=None):
    """Turnover universe + the date it was measured on.

    Reads `docs/liquid_universe.json` — the tiny sidecar `bake_liquid_universe.py` writes each evening
    in refresh-backtest-data.yml, where the freshly appended bin actually lives — and falls back to
    scanning the committed bin.

    The fallback is a LAST RESORT, not the normal path: `docs/sf_stock_data.bin` is a frozen snapshot
    on purpose (refresh-market-mood overwrites it in the runner but never commits it, and the real bin
    is ~193 MB — past GitHub's 100 MB file cap, so it CANNOT be committed fresh). Left to it this build
    dated its universe 2026-06-13 while prices ran to 2026-08-07: 41 newly-liquid names (SBIFUNDS,
    TURTLEMINT, MANIPALHOS …) were missing from the default universe and 28 names that had gone illiquid
    were still counted — 4.8% of 1,433, and growing every day the snapshot stayed frozen.

    BOTH PATHS ARE GUARDED, but at different moments: the recency guard lives inside scan_bin_universe(),
    so the sidecar is cut ALREADY-FILTERED and the fallback filters as it scans. A sidecar has no per-symbol
    dates, so it cannot be re-screened on read — `recencyDays` in the file is how a guarded bake identifies
    itself. A sidecar baked BEFORE the guard is still USED, not rejected: measured, it is 0.4% wrong (6 stale
    series of 1,447) where the frozen bin is 4.8% wrong, so falling back would trade a small defect for a
    bigger one. It says so loudly and self-heals the next time refresh-backtest-data.yml appends a day."""
    rename = rename if rename is not None else load_rename()
    try:
        S = json.load(open(LIQ, encoding="utf-8"))
        syms = {rename.get(s, s) for s in S["symbols"]}
        if syms and S.get("asOf"):
            if not S.get("recencyDays"):
                print(
                    f"  ⚠ {os.path.basename(LIQ)} was baked BEFORE the recency guard — stale series may still be in it; "
                    "it self-heals on the next refresh-backtest-data.yml append"
                )
            return syms, S["asOf"]
        print(f"  ⚠ {os.path.basename(LIQ)} present but empty — falling back to the frozen bin")
    except FileNotFoundError:
        pass
    except Exception as e:
        print(f"  ⚠ {os.path.basename(LIQ)} unreadable ({e}) — falling back to the frozen bin")
    U, end = scan_bin_universe(BIN, rename)
    print(f"  ⚠ liquid universe from the FROZEN committed bin (as of {end}) — sidecar missing")
    return U, end


def consistent(cur, base):
    cs, cc = cur
    bs, bc = base
    if cc is not None and bc is not None:
        return cc, bc
    if cs is not None and bs is not None:
        return cs, bs
    return None


MIN_N = 5  # don't publish a median computed over fewer than this many companies (not robust)


def median_yoy(pairs, min_n=MIN_N):
    """Per-company YoY %, Trendlyne's convention: (cur - base) / ABS(base).

    Dividing by |base| is what makes a swing from a LOSS to a profit read POSITIVE instead of
    sign-flipping — BHEL Q1FY27 gives (503.86 - -537.14)/537.14 = +193.80%, exactly the figure
    Trendlyne prints. This MIRRORS profitAt() in docs/stock-backtest.html + docs/backtest-engine.js
    (`yoy: (c-b)/Math.abs(b)*100`), which has always used it — the old `bv > 0` test here silently
    DROPPED every loss-base turnaround from the median instead. base == 0 is still skipped (÷0)."""
    ys = [(cv - bv) / abs(bv) * 100.0 for cv, bv in pairs if bv is not None and bv != 0 and cv is not None]
    return (round(statistics.median(ys), 1) if len(ys) >= min_n else None), len(ys)


def agg_total(pairs, min_n=MIN_N, drop_nonpos=False):
    """Index TOTAL growth, Trendlyne's rule: sum(now)/sum(ago)-1 over EVERY company that reported BOTH
    periods, negative bases INCLUDED (CONSOLIDATED-preferred basis).

    A negative base is REAL, not noise: BHEL's Q1FY26 op is -537.14 off a genuine loss quarter (PAT -455),
    and it is the same -537.14 Trendlyne holds. VERIFIED 2026-07-17 — TL's Nifty-500 Q1FY27 "Total Oper
    Profit Growth" card (20.70%) reproduces to the decimal as the sum of their own 35 printed rows ONLY
    with BHEL's base kept negative; back-deriving it as positive is what made it look like their card
    disagreed with their table.

    ⚠️ This REPLACES an old `base AND current > 0` filter, whose docstring wrongly claimed "revenue/op are
    unaffected (both always > 0)" — BHEL disproves that. The filter silently dropped such companies and
    read 18.07% for that same cell (vs 19.90% here). It was originally added because total PAT with loss
    bases looked implausible (MidSmallcap400 read 72%) — but that number is the arithmetic truth (an index
    whose members collectively earned less last year BECAUSE of losses really did grow that much), and
    Trendlyne itself never publishes a total-PAT % — it shows profit COUNTS. Prefer the median (or the
    counts) for profit; see DATA_RUNBOOK §11.

    drop_nonpos=True is used for PAT ONLY (see agg_quarter): net profit is a RESIDUAL that cancels to
    ~zero at index level, so summing losses in makes sum(ago) collapse and the ratio explode
    (Smallcap-250 Mar-2021 read 9841%). Trendlyne itself never publishes a total-PAT % for exactly this
    reason — it shows profit COUNTS. Revenue/op are gross aggregates and stay stable, so they follow
    TL's rule. DEGENERACY GUARD (all metrics): even summing everything, sum(ago) can be a near-zero
    residue of cancelling signs (Consumer Durables Jun-2021 op, a COVID-shut base) — a % off that is
    noise, not information, so require sum(ago) to be a real fraction of sum(|ago|) and return None
    otherwise (an honest gap in the chart beats a 2825% bar). See DATA_RUNBOOK §11."""
    pairs = [(n, a) for n, a in pairs if n is not None and a is not None]
    if drop_nonpos:
        pairs = [(n, a) for n, a in pairs if n > 0 and a > 0]
    sn = sum(n for n, a in pairs)
    sa = sum(a for n, a in pairs)
    sabs = sum(abs(a) for n, a in pairs)
    ok = sa > 0 and len(pairs) >= min_n and sa >= 0.25 * sabs
    return (round((sn / sa - 1) * 100, 1) if ok else None), len(pairs)


def agg_quarter(members, qe, pat, revop, min_n=MIN_N, include_fin=False):
    """Return (quarter-dict, reported). Each metric carries BOTH:
      median  = median of per-company YoY — 'typical company'
      total   = aggregate sum(now)/sum(ago)-1 — the index P&L (matches Trendlyne).
    Both are built from the SAME consistent() pair, so current and base are always on the same
    basis (con/con where both filed con, else std/std) — never std-now vs con-year-ago."""
    ya = yago(qe)
    reported = 0
    pat_pairs, rev_pairs, op_pairs, ebit_pairs = [], [], [], []  # median
    pat_tot, rev_tot, op_tot, ebit_tot = [], [], [], []  # total (same pairs)
    for s in members:
        pq = pat.get(s)
        if pq:
            cur_pat = pq.get(qe)
            if cur_pat and (cur_pat[0] is not None or cur_pat[1] is not None):
                reported += 1
                base_pat = pq.get(ya)
                if base_pat:
                    # ONE pair feeds BOTH the median and the total. consistent() is still
                    # CONSOLIDATED-PREFERRED (con/con where both periods filed con, else std/std) —
                    # which is what reconciles to Trendlyne's cards (TCS Q1FY27 rev 72,275 = con,
                    # not std 59,553). The point is that it picks the basis for the PAIR, not for
                    # each period independently: the old _cpref() ran per period, so a company that
                    # filed con last year but only std this year was compared std-vs-con —
                    # ICICIPRULI Jun-2026 (no con XBRL exists) read op 306.56/282.09 = +8.67%
                    # instead of the true std/std 306.56/292.22 = +4.91%.
                    pr = consistent(cur_pat, base_pat)
                    if pr:
                        pat_pairs.append(pr)
                        pat_tot.append(pr)
        rv = revop.get(s)
        if rv:
            cq, bq = rv.get(str(qe)), rv.get(str(ya))
            # Financials INCLUDED when include_fin (banks: rev = interest earned, op = pre-provision;
            # NBFCs: core rev + EBITDA) — matches Trendlyne's index cards. Mixed universes without the
            # flag exclude them (industrial rev/EBITDA aren't comparable to bank interest income).
            if cq and bq and (include_fin or (not cq[6] and not bq[6])):
                pr = consistent((cq[0], cq[1]), (bq[0], bq[1]))
                if pr:
                    rev_pairs.append(pr)
                    rev_tot.append(pr)
                po = consistent((cq[2], cq[3]), (bq[2], bq[3]))
                if po:
                    op_pairs.append(po)
                    op_tot.append(po)
                # EBIT (after-dep operating profit) lives at idx 7/8 — defensive for legacy 7-elem rows
                ce_s, ce_c = (cq[7] if len(cq) > 7 else None), (cq[8] if len(cq) > 8 else None)
                be_s, be_c = (bq[7] if len(bq) > 7 else None), (bq[8] if len(bq) > 8 else None)
                pe = consistent((ce_s, ce_c), (be_s, be_c))
                if pe:
                    ebit_pairs.append(pe)
                    ebit_tot.append(pe)
    rev_m, rev_n = median_yoy(rev_pairs, min_n)
    rev_t, rev_tn = agg_total(rev_tot, min_n)
    op_m, op_n = median_yoy(op_pairs, min_n)
    op_t, op_tn = agg_total(op_tot, min_n)
    ebit_m, ebit_n = median_yoy(ebit_pairs, min_n)
    ebit_t, ebit_tn = agg_total(ebit_tot, min_n)
    pat_m, pat_n = median_yoy(pat_pairs, min_n)
    pat_t, pat_tn = agg_total(pat_tot, min_n, drop_nonpos=True)
    return {
        "qe": qe,
        "label": quarter_label(qe),
        "reported": reported,
        "rev": {"median": rev_m, "n": rev_n, "total": rev_t, "tn": rev_tn},
        "op": {"median": op_m, "n": op_n, "total": op_t, "tn": op_tn},
        "ebit": {"median": ebit_m, "n": ebit_n, "total": ebit_t, "tn": ebit_tn},
        "pat": {"median": pat_m, "n": pat_n, "total": pat_t, "tn": pat_tn},
    }, reported


def main():
    rename = load_rename()
    U, end = build_liquid_universe(rename)
    print("liquid universe (alive, turnover>=%.1f cr): %d" % (TURN_FLOOR_CR, len(U)))

    fund = json.load(open(FUND))
    revop = json.load(open(REVOP))
    indices = json.load(open(INDICES, encoding="utf-8"))

    pat = {s: {r[0]: (r[1], r[3]) for r in rows} for s, rows in fund.items()}

    # ---- vision_fills overlay (2026-07-21): during an NSE XBRL outage the vision safety-net keeps
    # the RESULTS PAGE current, but this chart read only sf_fundamentals/sf_revop — so the season
    # bar starved at 44 reporters while the page showed 62 (the 2026-07-20 lockdown). Merge the
    # fills as a FALLBACK for quarters the XBRL stores don't have yet; real XBRL supersedes on its
    # next parse because we never overwrite an existing cell. Basis-aware: a "C" fill only pairs
    # against a consolidated year-ago base, "S" only standalone (consistent() picks the pair).
    try:
        vfill = json.load(open(os.path.join(ROOT, "docs", "vision_fills.json"), encoding="utf-8"))
    except Exception:
        vfill = {}
    vadd = 0
    for sym, qmap in vfill.items():
        for qk, rec in qmap.items():
            try:
                qe = int(qk)
            except Exception:
                continue
            basis = rec.get("basis") or ""

            def slot(v):
                if v is None:
                    return (None, None)
                return (None, v) if basis == "C" else ((v, None) if basis == "S" else (v, v))

            if rec.get("pat") is not None and qe not in pat.setdefault(sym, {}):
                pat[sym][qe] = slot(rec["pat"])
                vadd += 1
            if rec.get("rev") is not None or rec.get("op") is not None:
                qs = revop.setdefault(sym, {})
                if str(qe) not in qs:
                    base = qs.get(str(yago(qe)))
                    fin = (base[6] if isinstance(base, list) and len(base) > 6 else 0) or 0
                    rs, rc = slot(rec.get("rev"))
                    os_, oc = slot(rec.get("op"))
                    qs[str(qe)] = [rs, rc, os_, oc, None, None, fin, None, None]
    if vadd:
        print("vision_fills overlay: +%d PAT cells the XBRL stores don't have yet" % vadd)

    # candidate quarter-ends: Mar-2019 (earliest with a 2018 year-ago base) to latest
    cand = []
    y, m = 2019, 3
    while (y, m) <= (2026, 12):
        cand.append(y * 10000 + m * 100 + {3: 31, 6: 30, 9: 30, 12: 31}[m])
        m += 3
        if m > 12:
            m = 3
            y += 1

    def snap_as_of(snaps, ymd):
        chosen = None
        for snp in snaps:
            if snp.get("effectiveDate", "9") <= ymd:
                chosen = snp
        return {rename.get(s, s) for s in chosen["symbols"]} if chosen else set()

    def build(label, key, note, member_fn, min_rep, include_fin=False, member_fn_live=None):
        qs = []
        last_qe = last_members = None
        last_rep = 0  # newest quarter with any reporter (cand is chronological)
        for qe in cand:
            members = member_fn(qe)
            if not members:
                continue
            row, reported = agg_quarter(members, qe, pat, revop, include_fin=include_fin)  # robust MIN_N floor
            if reported > 0:
                last_qe, last_members, last_rep = qe, members, reported
            if reported >= min_rep:
                qs.append(row)
        # The CURRENT quarter shows from its very first filing and stays "in progress" until HALF
        # the universe has reported. Crossing min_rep alone isn't enough: early reporters are
        # bank-heavy, so an index can pass the gate (e.g. 6 of 500) while rev/EBITDA still have
        # fewer than MIN_N non-financial samples — the medians suppress to null and the chart
        # renders blank bars with no in-progress tag (live bug, Nifty 500 Q1FY27). While partial,
        # recompute over whatever sample exists (min_n=1) and flag it for the dimmed/amber UI.
        if last_qe is not None and last_rep < 0.5 * len(last_members):
            # In-progress quarter: use the LATEST index snapshot, not the quarter-end one —
            # reconstitutions land DURING the reporting season (ICICIAMC entered Nifty 500 on
            # 2026-07-17, mid-Q1FY27 season) and Trendlyne's live dashboard counts current
            # members. Finished quarters keep point-in-time membership (survivorship-free).
            live_members = member_fn_live(last_qe) if member_fn_live else last_members
            row, _ = agg_quarter(live_members, last_qe, pat, revop, min_n=1, include_fin=include_fin)
            row["partial"] = True
            qs = [r for r in qs if r["qe"] != last_qe] + [row]
        qs.sort(key=lambda r: r["qe"])
        return {"key": key, "label": label, "note": note, "quarters": qs, "fin": include_fin}

    # Financials are INCLUDED in every universe's rev/op totals (bank rev = interest earned, op =
    # pre-provision operating profit; NBFC rev = core revenue, op = EBITDA) — matches Trendlyne's
    # index result-analysis cards to the paisa (Nifty 500 Q1FY27: rev 13.8, oper profit 13.3).
    # Verified 2026-07-10. The op bar for a mixed universe therefore sums industrial EBITDA with
    # bank pre-provision profit — that aggregate == Trendlyne's "Oper Profit" card (their separate
    # "EBIDT" card is a proprietary before-depreciation calc we don't reproduce).
    universes = []
    # 1) the liquid universe (default)
    universes.append(
        build(
            "All liquid stocks (₹1cr+/day)",
            "liquid",
            "Currently-listed companies trading ≥ ₹1 cr/day (median, ~250 sessions) — %d names." % len(U),
            lambda qe: U,
            200,
            include_fin=True,
        )
    )
    # 2) every index, point-in-time membership
    FIN_UNIVERSES = {"Nifty Bank", "Nifty PSU Bank"}
    for index, snaps in indices.items():
        if not isinstance(snaps, list) or not snaps:
            continue
        note = (
            f"Point-in-time {index} members at each quarter's rebalance (survivorship-free)."
            " Revenue = interest earned; the Operating Profit bar = pre-provision operating profit."
            if index in FIN_UNIVERSES
            else f"Point-in-time {index} members at each quarter's rebalance (survivorship-free)."
            " Banks/NBFCs are included: their revenue = interest earned, operating profit = pre-provision."
        )
        uni = build(
            index,
            index,
            note,
            (lambda snps: lambda qe: snap_as_of(snps, iso(qe)))(snaps),
            5,
            include_fin=True,
            member_fn_live=(lambda snps: lambda qe: snap_as_of(snps, "9999-99-99"))(snaps),
        )
        # CURRENT members (latest snapshot, rename-mapped) — powers the quarterly-results page's
        # Season-Trends quarter click-through for universes the main table's index bitmask can't
        # express (sectoral indices, Nifty 200, Midcap 50 …). Current-membership on purpose: the
        # All Results universe filter is a display filter, not point-in-time (DATA_RUNBOOK §15).
        uni["members"] = sorted(snap_as_of(snaps, "9999-99-99"))
        universes.append(uni)

    universes = [u for u in universes if u["quarters"]]
    for u in universes:
        q = u["quarters"]
        print(
            "  %-24s %2d quarters  latest %s reported=%d"
            % (u["label"], len(q), q[-1]["label"] if q else "-", q[-1]["reported"] if q else 0)
        )

    ist = datetime.datetime.utcnow() + datetime.timedelta(hours=5, minutes=30)
    payload = {
        "defaultUniverse": "liquid",
        "basis": "YoY vs the year-ago quarter (positive base). PAT = consolidated owners-attributable where "
        "filed, else standalone. Total = consolidated-preferred aggregate (matches Trendlyne). Revenue "
        "& Operating profit include banks/NBFCs (bank rev = interest earned, op = pre-provision profit). "
        "Index universes use point-in-time membership (whoever was in the index at each quarter's rebalance).",
        # NOT a price date, and NOT an as-of for anything the chart plots: the bars are rev/op/PAT YoY
        # out of sf_fundamentals + sf_revop, which `updated` below timestamps. This dates ONE thing —
        # the turnover snapshot that picks the "liquid" universe's members. Index universes don't use
        # it at all (their membership comes from indices_history.json), so the page must NOT stamp it
        # on them: it read "Nifty 500 · prices as of 2026-06-13" over data rebuilt 20 min earlier.
        "universeAsOf": end,
        # when THIS build ran — distinct from universeAsOf (the turnover snapshot). Lets the page show
        # "refreshed HH:MM IST" so a stale open tab doesn't read as a dead pipeline (runbook §11).
        "updated": ist.strftime("%Y-%m-%d %H:%M IST"),
        "universes": universes,
    }
    json.dump(payload, open(OUT, "w"), separators=(",", ":"))
    print("Wrote %s (%d universes)" % (OUT, len(universes)))


